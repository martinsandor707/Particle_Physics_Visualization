/*
 * The benchmark catalogue: every figure of the Hungarian training report `models_performance.md`
 * (the 36 calorimeter models: 4 species x 3 tasks x 3 coordinate frames), as data.
 *
 * Provenance. The numbers are the report's own, copied with the decimal comma turned into a point and
 * never re-rounded, in the report's unit (named by a `unit` field; display conversion, such as radians to
 * milliradians, happens elsewhere). The proton results are dated 2026-09-24; the muon, electron and pion
 * results come from the report's later section on the new particle datasets. They are documented point
 * estimates: the report prints no interval, no seed spread and no repetition for any of them, and nothing
 * here derives one. `tests/test_benchmark_catalog.py` parses the report's tables and pins every number of
 * this file to them, and counts every numeric token of every results table to prove none is left out.
 *
 * Conventions.
 *  - A qualified scalar is { value, qualifier }: qualifier null (exact as printed), 'approx' (the report's
 *    "≈" or "körül"), 'about' ("~"), 'lt' (printed only as "< bound": value null, bound 0), 'none' (the report
 *    gives nothing). R-squared fields always use this form; a plain number is a plain printed number.
 *  - Formulas: `source` is the report's text verbatim (Hungarian decimal commas and feature names for the
 *    proton), `ascii` the explicit form (decimal points, ^2 for the square, * for every product, English
 *    feature keys, the right-hand side only), `tex` the same in the math.js subset. A formula the report
 *    does not give has `absent: true` and null ascii and tex.
 *  - Feature keys are English (FEATURES); a mapping the report does not state is `inferred: true`.
 *  - The report's frames `absolute`, `trans`, `local` are the dashboard's Absolute, Per-shower translated
 *    and Local.
 *  - Hit-level or particle-level: see OVERLAP[species].level. The proton's overlap rows are titled hit-level
 *    for every task; the new species' angle and energy rows are per particle; every segmentation row is
 *    hit-level and weighted by the event energy.
 *  - validationParticles is 2 per combined event: stated for the proton (8,130 for 4,065), derived here for
 *    the new species (8,000 for 4,000).
 *  - Printed decimals (`dp`, the fix round of 2026-11-05). A JS number drops trailing zeros (the report's
 *    1,0000 becomes 1), and a reader must see the report's rounding to know which differences it does not
 *    resolve. So every reported non-integer carries the count of decimals the report prints: a qualified
 *    scalar holds its own `dp`; a row's plain numbers are counted in the row's `dp` map, keyed by field
 *    (OVERLAP rows: `dp: { all, bins: [5] }`); INDECISION.dp and STARVATION.meanMomentum.dp count the prose's
 *    decimals (the ambiguous shares are printed as whole percentages); paramsMillionsDp the "5,90 M" form.
 *    A field with no count is an integer. Formatting a value with value.toFixed(dp) reproduces the report's
 *    token exactly (decimal point for its comma); the test pins that for every token of every results table.
 *  - Added fields beyond the contract: DISTILLATION[].pysr.featureMapInferred, ARCHITECTURE.*.paramsMillions,
 *    MOMENTUM_WINDOWS[].oneSigned, THROUGHPUT.notReportedFor, DEFINITIONS, DATASETS.*.combinedEvents, the `dp`
 *    counts above and ARCHITECTURE.tasks.*.paramsMillionsDp.
 *
 * Pure data: no imports, every export deep-frozen.
 */

function deepFreeze(value) {
  if (value !== null && typeof value === 'object' && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const child of Object.values(value)) deepFreeze(child);
  }
  return value;
}

